/**
 * Render an inline SVG icon.
 * @param {keyof typeof PATHS} name
 * @param {{ size?: number, className?: string, strokeWidth?: number }} [opts]
 * @returns {string} SVG markup
 */
export function icon(name, opts = {}) {
  const { size = 16, className = '', strokeWidth = 2 } = opts;
  const body = PATHS[name] || PATHS.info;
  return `<svg class="pc-icon ${className}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

export function hasIcon(name) {
  return Object.prototype.hasOwnProperty.call(PATHS, name);
}

/**
 * Fill every [data-icon] element in a tree with its SVG.
 * Lets static markup declare icons without inlining path data.
 */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach(el => {
    el.innerHTML = icon(el.dataset.icon, { size: Number(el.dataset.iconSize) || 16 });
    el.removeAttribute('data-icon');
  });
}

